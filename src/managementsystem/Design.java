    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        if (currentStudent == null) {
        jTextArea1.setText("Create Student first!");
        return;
    }
    try {
        // SAME call as your Button 4 in the photo - static method
        String report = ReportGenerator.generateReport(currentStudent, gradeList, attendance);

        // Save the FULL report, not just ID and Name
        FileExporter exporter = new FileExporter();
        exporter.exportReport(report);

        jTextArea1.setText(report + "\n\n--- Exported to report.csv in project folder ---");
    } catch (Exception e) {
        jTextArea1.setText("Export error: " + e.getMessage() + "\nPlease make sure you added Student, Grade and Attendance");
    }
    }//GEN-LAST:event_jButton5ActionPerformed

