    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
         try {
        //  Read from text fields in the picture
        String code = jTextField3.getText().trim();      
        String subject = jTextField4.getText().trim();  
        double mark = Double.parseDouble(jTextField5.getText().trim());
        double weight = Double.parseDouble(jTextField6.getText().trim()); 

        //  Create grade (3-param constructor)
        Grade g = new Grade(code, subject, mark);
        
       
        g.setWeight(weight);

        //  Add to list
        gradeList.add(g);

        // Show in  box
        jTextArea1.setText("GRADE ADDED:\n" +
                          "Code: " + code + "\n" +
                          "Subject: " + subject + "\n" +
                          "Mark: " + mark + "\n" +
                          "Weight: " + weight + "\n" +
                          "Total grades: " + gradeList.size());

    } catch (NumberFormatException ex) {
        jTextArea1.setText("ERROR: Mark and Weight must be numbers!\n" +
                          "You typed letters in Mark or Weight box.\n" +
                          "Error: " + ex.getMessage());
    } catch (Exception ex) {
        jTextArea1.setText("ERROR: " + ex.getMessage());
    }
         try {
    Connection con = Student.getConnection();
    con.createStatement().executeUpdate("INSERT INTO grades VALUES ('" + jTextField1.getText() + "', '" + jTextField3.getText() + "', '" + jTextField4.getText() + "', " + jTextField5.getText() + ", " + jTextField6.getText() + ")");
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
     try {
        int attended = Integer.parseInt(jTextField7.getText().trim());
        int total = Integer.parseInt(jTextField8.getText().trim());

        if (total == 0) {
            jTextArea1.setText("Total cannot be 0");
            return;
        }

        Attendance att = new Attendance();
        att.setAttended(attended);
        att.setTotal(total);
        
        attendance = att;

        jTextArea1.setText("Attendance saved: " + attended + "/" + total);

    } catch (NumberFormatException e) {
        jTextArea1.setText("Type numbers only for Attended and Total");
    }
     try {
    Connection con = Student.getConnection();
    con.createStatement().executeUpdate("INSERT INTO attendance VALUES ('" + jTextField1.getText() + "', " + jTextField7.getText() + ", " + jTextField8.getText() + ")");
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_jButton3ActionPerformed

